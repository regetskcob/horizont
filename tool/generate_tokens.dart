// Generates flutter/lib/src/tokens.g.dart from tokens/horizont.json and the
// symbol codepoints in icons/material-symbols.json. Plain Dart, no packages:
//
//   dart run tool/generate_tokens.dart
//
// CI runs it and fails when the committed file differs (stale tokens).

import 'dart:convert';
import 'dart:io';

final _root = File(Platform.script.toFilePath()).parent.parent;

void main() {
  final tokens = _read('tokens/horizont.json');
  final symbols = _read('icons/material-symbols.json');
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_tokens.dart from tokens/horizont.json')
    ..writeln('// and icons/material-symbols.json. Do not edit; change the JSON and')
    ..writeln('// run `dart run tool/generate_tokens.dart`.')
    ..writeln('//')
    ..writeln('// Tier 1 of the system: raw values. Widgets never read these, they')
    ..writeln('// read HorizontTheme.of(context).')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// Version of the tokens this file was generated from.')
    ..writeln("const String horizontTokensVersion = '${tokens['version']}';")
    ..writeln();

  final color = tokens['color'] as Map<String, dynamic>;
  final neutral = color['neutral'] as Map<String, dynamic>;
  final status = color['status'] as Map<String, dynamic>;
  final products = color['product'] as Map<String, dynamic>;

  _class(out, 'HzNeutrals', 'The neutral colours of one brightness.',
      (neutral['light'] as Map<String, dynamic>).keys);
  _class(out, 'HzStatus', 'The status colours of one brightness.',
      (status['light'] as Map<String, dynamic>).keys);
  _class(out, 'HzAccent', 'The accent of one product in one brightness.',
      ((products.values.first as Map<String, dynamic>)['light'] as Map<String, dynamic>).keys);

  out
    ..writeln('/// Raw colour values per brightness.')
    ..writeln('abstract final class HzColors {');
  for (final mode in ['light', 'dark']) {
    _const(out, 'neutral${_cap(mode)}', 'HzNeutrals', neutral[mode] as Map<String, dynamic>);
    _const(out, 'status${_cap(mode)}', 'HzStatus', status[mode] as Map<String, dynamic>);
  }
  final data = color['data'] as Map<String, dynamic>;
  for (final mode in ['light', 'dark']) {
    final ramp = (data[mode] as List<dynamic>).cast<String>();
    out
      ..writeln('  /// Sequential data ramp, $mode: little to much.')
      ..writeln('  static const List<Color> dataRamp${_cap(mode)} = [')
      ..writeAll(ramp.map((v) => '    Color(0xFF${v.substring(1).toUpperCase()}),\n'))
      ..writeln('  ];');
  }
  out.writeln('}\n');

  final scrim = color['scrim'] as Map<String, dynamic>;
  out
    ..writeln('/// The dark ground under photos and media (lightbox, photo viewer,')
    ..writeln('/// webcams), the same in light and dark.')
    ..writeln('abstract final class HzScrim {');
  for (final k in ['bg', 'text', 'text-muted']) {
    out
      ..writeln('  /// `$k`')
      ..writeln('  static const Color ${_camel(k)} = Color(0xFF${(scrim[k] as String).substring(1).toUpperCase()});');
  }
  out
    ..writeln('  /// Opacity of the bars over the picture (black at ${scrim['bar-alpha']}).')
    ..writeln('  static const double barAlpha = ${_num(scrim['bar-alpha'])};')
    ..writeln('}\n');

  out
    ..writeln('/// The products of Horizont with their accents.')
    ..writeln('enum HorizontProduct {');
  final ids = products.keys.toList();
  for (var i = 0; i < ids.length; i++) {
    final p = products[ids[i]] as Map<String, dynamic>;
    final neutralDark = p['neutralDark'] as Map<String, dynamic>?;
    out
      ..writeln('  /// ${p['name']}: ${p['role']}.')
      ..writeln('  ${_camel(ids[i])}(')
      ..writeln("    displayName: '${p['name']}',")
      ..writeln("    accentName: '${p['accentName']}',")
      ..write('    light: ')
      ..write(_ctor('HzAccent', p['light'] as Map<String, dynamic>, 4))
      ..writeln(',')
      ..write('    dark: ')
      ..write(_ctor('HzAccent', p['dark'] as Map<String, dynamic>, 4))
      ..writeln(',');
    if (neutralDark != null) {
      out
        ..write('    neutralDark: ')
        ..write(_ctor('HzNeutrals', neutralDark, 4))
        ..writeln(',');
    }
    out.writeln('  )${i == ids.length - 1 ? ';' : ','}');
  }
  out.writeln('''

  const HorizontProduct({
    required this.displayName,
    required this.accentName,
    required this.light,
    required this.dark,
    this.neutralDark,
  });

  /// The product's name as written in the UI.
  final String displayName;

  /// The name of the accent colour (Tinte, Tanne, Bus, Signalgelb, Backstein).
  final String accentName;

  /// The accent in light mode.
  final HzAccent light;

  /// The accent in dark mode.
  final HzAccent dark;

  /// Own neutrals in dark mode (only Panzergefecht's Gelände), else null.
  final HzNeutrals? neutralDark;
}
''');

  final hosts = (color['host'] as Map<String, dynamic>?) ?? const {};
  out
    ..writeln('/// Hosts that embed a product and lend it their neutrals, e.g. Home')
    ..writeln("/// Assistant's Ingress. Accent, status and type stay Horizont.")
    ..writeln('enum HorizontHost {');
  final hostIds = hosts.keys.toList();
  for (var i = 0; i < hostIds.length; i++) {
    final h = hosts[hostIds[i]] as Map<String, dynamic>;
    out
      ..writeln('  /// ${h['name']}: ${h['role']}.')
      ..writeln('  ${_camel(hostIds[i])}(')
      ..writeln("    displayName: '${h['name']}',")
      ..write('    light: ')
      ..write(_ctor('HzNeutrals', h['light'] as Map<String, dynamic>, 4))
      ..writeln(',')
      ..write('    dark: ')
      ..write(_ctor('HzNeutrals', h['dark'] as Map<String, dynamic>, 4))
      ..writeln(',')
      ..writeln('  )${i == hostIds.length - 1 ? ';' : ','}');
  }
  out.writeln('''

  const HorizontHost({required this.displayName, required this.light, required this.dark});

  /// The host's name.
  final String displayName;

  /// The host's neutrals in light mode.
  final HzNeutrals light;

  /// The host's neutrals in dark mode.
  final HzNeutrals dark;
}
''');

  _numbers(out, 'HzSpace', 'Spacing on the 4 grid.', 's', tokens['space'] as Map<String, dynamic>);
  _numbers(out, 'HzRadius', 'Corner radii.', 'r', tokens['radius'] as Map<String, dynamic>);
  _numbers(out, 'HzLine', 'Line widths.', '', tokens['line'] as Map<String, dynamic>);
  _numbers(out, 'HzSize', 'Sizes of targets, rows, columns and bars.', '', tokens['size'] as Map<String, dynamic>);
  _numbers(out, 'HzIconSize', 'Icon sizes: in a badge, inline in text, in rows and rails, in bars and buttons, in the tab bar.', '', tokens['icon-size'] as Map<String, dynamic>);
  _numbers(out, 'HzBreakpoint', 'Window size classes by available width.', '', tokens['breakpoint'] as Map<String, dynamic>);
  _numbers(out, 'HzTv', 'The television: safe margins, type scale, focus ring and focus growth.', '', tokens['tv'] as Map<String, dynamic>);

  final motion = tokens['motion'] as Map<String, dynamic>;
  out
    ..writeln('/// Durations and curves. Collapse to zero under reduced motion.')
    ..writeln('abstract final class HzMotion {');
  for (final k in ['fast', 'base', 'slow', 'calm']) {
    out
      ..writeln('  /// ${motion[k]} ms.')
      ..writeln('  static const Duration $k = Duration(milliseconds: ${motion[k]});');
  }
  for (final k in ['standard', 'exit', 'settle']) {
    final v = RegExp(r'[\d.]+').allMatches(motion[k] as String).map((m) => m[0]).join(', ');
    out
      ..writeln('  /// ${motion[k]}.')
      ..writeln('  static const Cubic $k = Cubic($v);');
  }
  out.writeln('}\n');

  out
    ..writeln('/// Font families bundled with the package.')
    ..writeln('abstract final class HzFont {')
    ..writeln('  /// The package that bundles the fonts.')
    ..writeln("  static const String package = 'horizont';")
    ..writeln('  /// Literata: what is read.')
    ..writeln("  static const String serif = 'Literata';")
    ..writeln('  /// Mona Sans: what is operated.')
    ..writeln("  static const String sans = 'MonaSans';")
    ..writeln("  /// Mona Sans Display Expanded: Panzergefecht's headlines.")
    ..writeln("  static const String sansExpanded = 'MonaSansDisplayExpanded';")
    ..writeln('  /// Monaspace Argon: what is measured.')
    ..writeln("  static const String mono = 'MonaspaceArgon';")
    ..writeln('  /// Material Symbols Sharp, weight 300, cut to icons/material-symbols.txt.')
    ..writeln("  static const String symbols = 'MaterialSymbolsSharp';")
    ..writeln('}\n');

  out.writeln('''/// One step of the type scale. Tracking is in em, as in the tokens.
@immutable
class HzTypeSpec {
  /// Creates a step of the type scale.
  const HzTypeSpec({
    required this.family,
    required this.size,
    required this.line,
    required this.weight,
    required this.tracking,
    this.upper = false,
  });

  /// Font family (one of [HzFont]).
  final String family;

  /// Font size in logical pixels at text scale 1.
  final double size;

  /// Line height in logical pixels at text scale 1.
  final double line;

  /// Font weight.
  final FontWeight weight;

  /// Letter spacing in em.
  final double tracking;

  /// Whether the text is set in capitals (Kennung).
  final bool upper;
}
''');
  final families = {'serif': 'HzFont.serif', 'sans': 'HzFont.sans', 'mono': 'HzFont.mono'};
  out
    ..writeln('/// The type scale.')
    ..writeln('abstract final class HzType {');
  (tokens['type'] as Map<String, dynamic>).forEach((k, v) {
    final t = v as Map<String, dynamic>;
    out
      ..writeln('  /// ${t['family']} ${t['size']}/${t['line']}, ${t['weight']}.')
      ..writeln('  static const HzTypeSpec ${_camel(k)} = HzTypeSpec(')
      ..writeln('    family: ${families[t['family']]},')
      ..writeln('    size: ${_num(t['size'])},')
      ..writeln('    line: ${_num(t['line'])},')
      ..writeln('    weight: FontWeight.w${t['weight']},')
      ..writeln('    tracking: ${_num(t['tracking'])},')
      ..writeln(t['upper'] == true ? '    upper: true,' : '')
      ..writeln('  );');
  });
  out.writeln('}\n');

  out
    ..writeln('/// The Material Symbols Sharp icons bundled with the package.')
    ..writeln('abstract final class HorizontSymbols {');
  symbols.forEach((name, code) {
    out
      ..writeln('  /// `$name`')
      ..writeln('  static const IconData ${_camel(name)} = IconData($code, '
          'fontFamily: HzFont.symbols, fontPackage: HzFont.package);');
  });
  out.writeln('}');

  final text = out.toString().replaceAll(RegExp(r'\n\n\n+'), '\n\n').replaceAll(',\n\n  );', ',\n  );');
  File('${_root.path}/flutter/lib/src/tokens.g.dart').writeAsStringSync(text);
  stdout.writeln('wrote flutter/lib/src/tokens.g.dart (tokens ${tokens['version']}, ${symbols.length} symbols)');
}

Map<String, dynamic> _read(String path) =>
    jsonDecode(File('${_root.path}/$path').readAsStringSync()) as Map<String, dynamic>;

void _class(StringBuffer out, String name, String doc, Iterable<String> keys) {
  out
    ..writeln('/// $doc')
    ..writeln('@immutable')
    ..writeln('class $name {')
    ..writeln('  /// Creates the set.')
    ..writeln('  const $name({')
    ..writeAll(keys.map((k) => '    required this.${_camel(k)},\n'))
    ..writeln('  });');
  for (final k in keys) {
    out
      ..writeln()
      ..writeln('  /// `$k`')
      ..writeln('  final Color ${_camel(k)};');
  }
  out.writeln('}\n');
}

void _const(StringBuffer out, String field, String type, Map<String, dynamic> values) {
  out
    ..writeln('  /// $type, $field.')
    ..write('  static const $type $field = ')
    ..write(_ctor(type, values, 2))
    ..writeln(';');
}

String _ctor(String type, Map<String, dynamic> values, int indent) {
  final pad = ' ' * (indent + 2);
  final b = StringBuffer('$type(\n');
  values.forEach((k, v) {
    if (k.startsWith('_')) return;
    b.writeln('$pad${_camel(k)}: Color(0xFF${(v as String).substring(1).toUpperCase()}),');
  });
  return '$b${' ' * indent})';
}

void _numbers(StringBuffer out, String name, String doc, String prefix, Map<String, dynamic> values) {
  out
    ..writeln('/// $doc')
    ..writeln('abstract final class $name {');
  values.forEach((k, v) {
    if (k.startsWith('_')) return;
    out
      ..writeln('  /// $v')
      ..writeln('  static const double ${prefix.isEmpty ? _camel(k) : '$prefix$k'} = ${_num(v)};');
  });
  out.writeln('}\n');
}

String _num(Object? v) {
  final n = v! as num;
  return n == n.roundToDouble() ? '${n.toInt()}.0' : '$n';
}

String _camel(String s) {
  final parts = s.split(RegExp(r'[-_]'));
  return parts.first + parts.skip(1).map(_cap).join();
}

String _cap(String s) => s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);
